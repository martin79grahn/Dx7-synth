// op(coarse, fine, outputLevel, rates, levels, extra)
const op = (fc, ff, ol, r, l, x = {}) => ({
  r, l, bp: 39, ld: 0, rd: 0, lc: 0, rc: 0, rs: 2, ams: 0, kvs: 2, ol, mode: 0, fc, ff, det: 7, ...x,
});
const off = () => op(1, 0, 0, [99, 99, 99, 99], [99, 99, 99, 0]);

function voice(name, alg, fb, ops, x = {}) {
  const v = initVoice();
  return {
    ...v, name, alg: alg - 1, fb, ops, ...x,
    lfo: { ...v.lfo, ...(x.lfo || {}) },
    peg: x.peg || v.peg,
  };
}

